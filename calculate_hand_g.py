def inverse_homogeneous(T):
    """
    计算齐次变换矩阵 T 的逆矩阵。
    T 为 4×4 矩阵，格式为 [R, t; 0, 1]
    返回 T^{-1} = [R^T, -R^T t; 0, 1]
    """
    R = T[:3, :3]
    t = T[:3, 3]
    T_inv = np.eye(4)
    T_inv[:3, :3] = R.T
    T_inv[:3, 3] = -np.dot(R.T, t)
    return T_inv

